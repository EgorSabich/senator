"""Stage 3 UI walkthrough in headless Chromium: login, set password, add employees, write/publish/compare a lesson,
managers, audit, phone layout. Needs a fresh server with owner egor.wlasciciel / TymczasoweHaslo1 (see docs/TESTING.md).
Screenshots go to $SHOTS_DIR. Prints NO_ERRORS when the browser saw no page errors."""
import os, sys
from playwright.sync_api import sync_playwright

BASE = os.environ.get("ACADEMY_URL", "http://localhost:8797")
OUT = os.environ.get("SHOTS_DIR", "/tmp/academy-shots")
os.makedirs(OUT, exist_ok=True)
errors = []

def shot(page, name):
    page.screenshot(path=f"{OUT}/{name}.png", full_page=True)

with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={"width": 1280, "height": 860}, locale="pl-PL")
    page = ctx.new_page()
    # Google Fonts are unreachable in the sandbox, and /api/auth/me answers 401 before login — both are expected noise.
    page.on("console", lambda m: errors.append(f"console {m.type}: {m.text}") if m.type in ("error",) and "ERR_TUNNEL_CONNECTION_FAILED" not in m.text and "401 (Unauthorized)" not in m.text else None)
    page.on("pageerror", lambda e: errors.append(f"pageerror: {e}"))

    page.goto(BASE + "/")
    page.get_by_label("Login").fill("egor.wlasciciel")
    page.get_by_label("PIN lub hasło").fill("TymczasoweHaslo1")
    shot(page, "01-login")
    page.get_by_role("button", name="Zaloguj się").click()
    page.get_by_role("heading", name="Ustaw swoje hasło").wait_for()
    page.get_by_label("Obecne hasło").fill("TymczasoweHaslo1")
    page.get_by_label("Nowe hasło").fill("NoweHasloEgora2026")
    page.get_by_label("Powtórz").fill("NoweHasloEgora2026")
    shot(page, "02-change")
    page.get_by_role("button", name="Zapisz").click()
    page.get_by_role("heading", name="Pracownicy").wait_for()

    # add employee
    page.get_by_role("button", name="Dodaj pracownika").first.click()
    page.get_by_label("Imię").fill("Anna")
    page.get_by_label("Nazwisko").fill("Kowalska")
    page.get_by_role("dialog").get_by_role("button", name="Dodaj pracownika").click()
    page.get_by_text("Dane do pierwszego logowania").wait_for()
    shot(page, "03-secret-card")
    page.get_by_role("button", name="Zamknij").click()
    page.get_by_role("button", name="Dodaj pracownika").first.click()
    page.get_by_label("Imię").fill("Łukasz")
    page.get_by_label("Nazwisko").fill("Żółć")
    page.get_by_role("dialog").get_by_role("button", name="Dodaj pracownika").click()
    page.get_by_role("button", name="Zamknij").click()
    page.wait_for_timeout(400)
    shot(page, "04-employees")

    # content
    page.get_by_role("link", name="Materiały").first.click()
    page.get_by_role("button", name="Nowy materiał").click()
    page.get_by_label("Tytuł").fill("Serwis stołu")
    page.get_by_label("Sekcja").fill("Standardy serwisu")
    page.get_by_role("dialog").get_by_role("button", name="Nowy materiał").click()
    page.get_by_role("toolbar").wait_for()
    ed = page.locator(".ProseMirror")
    ed.click()
    page.keyboard.type("Detale przy stole decydują o tym, czy gość czuje zwykłą obsługę, czy serwis premium.")
    page.keyboard.press("Enter")
    page.get_by_role("button", name="Ważne").click()
    page.keyboard.type("Talerz zabieramy od razu, gdy dany gość skończył jeść.")
    page.keyboard.press("Enter")
    page.keyboard.press("Enter")
    page.get_by_role("button", name="Kroki").click()
    page.keyboard.type("Zabierz talerz razem ze sztućcami.")
    page.keyboard.press("Enter")
    page.keyboard.type("Podaj czystą serwetkę ze sztućcami.")
    page.wait_for_timeout(2200)
    shot(page, "05-editor")
    page.get_by_role("button", name="Opublikuj").first.click()
    page.get_by_role("dialog").wait_for()
    shot(page, "06-publish-first")
    page.get_by_role("dialog").get_by_role("button", name="Opublikuj").click()
    page.get_by_text("Opublikowano.").wait_for()
    # second version
    ed.click()
    page.keyboard.press("Control+End")
    page.keyboard.press("Enter")
    page.keyboard.press("Enter")
    page.keyboard.type("W rękach nosimy maksymalnie 2 talerze.")
    page.wait_for_timeout(2200)
    page.get_by_role("button", name="Opublikuj").first.click()
    shot(page, "07-publish-level")
    page.get_by_label("Istotna").check()
    page.get_by_label("Opis zmiany (opcjonalnie)").fill("Dodano zasadę o 2 talerzach")
    page.get_by_role("dialog").get_by_role("button", name="Opublikuj").click()
    page.get_by_text("wersja 2").first.wait_for()
    page.wait_for_timeout(300)
    shot(page, "08-after-publish")
    page.get_by_role("button", name="Porównaj z poprzednią").first.click()
    page.get_by_role("dialog").wait_for()
    page.wait_for_timeout(500)
    shot(page, "09-compare")
    page.keyboard.press("Escape")

    page.get_by_role("link", name="Materiały").first.click()
    page.wait_for_timeout(500)
    shot(page, "10-content-list")
    page.get_by_role("link", name="Menedżerowie").first.click()
    page.get_by_role("button", name="Dodaj menedżera").click()
    page.get_by_label("Imię").fill("Marek")
    page.get_by_label("Nazwisko").fill("Nowak")
    page.get_by_role("dialog").get_by_role("button", name="Dodaj menedżera").click()
    page.get_by_role("button", name="Zamknij").click()
    page.wait_for_timeout(400)
    shot(page, "11-managers")
    page.get_by_role("link", name="Dziennik").first.click()
    page.wait_for_timeout(500)
    shot(page, "12-audit")

    # mobile
    m = b.new_context(viewport={"width": 390, "height": 844}, locale="pl-PL", storage_state=ctx.storage_state())
    mp = m.new_page()
    mp.on("pageerror", lambda e: errors.append(f"pageerror mobile: {e}"))
    mp.goto(BASE + "/panel/pracownicy")
    mp.get_by_role("heading", name="Pracownicy").wait_for()
    mp.wait_for_timeout(400)
    shot(mp, "13-mobile-employees")
    mp.goto(BASE + "/panel/materialy")
    mp.wait_for_timeout(600)
    mp.get_by_text("Serwis stołu").click()
    mp.get_by_role("toolbar").wait_for()
    mp.wait_for_timeout(500)
    shot(mp, "14-mobile-editor")
    b.close()

print("\n".join(errors) if errors else "NO_ERRORS")
